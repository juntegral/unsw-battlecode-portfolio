#!/usr/bin/env python3
"""Generate bot/mapdb.hpp from public map files (online pool + bundled maps).
Edge keys: H(x,y) = north side of tile (x,y); V(x,y) = west side of tile (x,y); wrap-merged."""
import glob, hashlib, os, sys
R = "~/01. Project/개인 프로젝트/UNSW"
srcs = sorted(glob.glob(R + "/maps/online-20260927/*.map")) + sorted(glob.glob(R + "/maps/online/*.map")) + sorted(glob.glob(R + "/lineages/g2/maps/*.map"))
seen = {}
out = []
for f in srcs:
    txt = open(f).read()
    h = hashlib.sha1(txt.encode()).hexdigest()
    if h in seen: continue
    seen[h] = f
    W = H = 0; sym = 0; name = os.path.basename(f)[:-4]; kinds = {}; pids = {}; tiles = {}; dragons = []
    for l in txt.split("\n"):
        p = l.split()
        if not p: continue
        if p[0] == "MAP": W, H = int(p[1]), int(p[2])
        elif p[0] == "MAP_NAME": name = " ".join(p[1:])
        elif p[0] == "SYMMETRY": sym = {"y": 1, "x": 2, "xy": 3}.get(p[1], 0)
        elif p[0] == "EDGE": kinds[int(p[1])] = int(p[2]); pids[int(p[1])] = int(p[3])
        elif p[0] == "TILE": tiles[(int(p[1]), int(p[2]))] = (int(p[3]), int(p[4]))
        elif p[0] == "DRAGON": dragons.append([int(v) for v in p[1:]])
    N = W * H; rl = W + 1
    hk = [0] * N; vk = [0] * N; hp = [-1] * N; vp = [-1] * N
    conflicts = 0
    def put(arrk, arrp, key, idx):
        global conflicts
        k = kinds.get(idx, 0); pid = pids.get(idx, -1)
        if k == 0: return
        if arrk[key] and (arrk[key] != k or arrp[key] != pid):
            print("conflict", name, key, file=sys.stderr)
        arrk[key] = k; arrp[key] = pid if k == 2 else -1
    for y in range(H + 1):
        for x in range(W + 1):
            hi = (2 * y) * rl + x
            if x < W: put(hk, hp, (y % H) * W + x, hi)
            if y < H:
                vi = (2 * y + 1) * rl + x
                put(vk, vp, y * W + (x % W), vi)
    edges = "".join(".wp"[hk[i]] + ".wp"[vk[i]] for i in range(N))
    portals = []
    for i in range(N):
        if hk[i] == 2: portals += [0, i, hp[i]]
        if vk[i] == 2: portals += [1, i, vp[i]]
    cls = []; clsidx = {}; gap = []
    for y in range(H):
        for x in range(W):
            mn, mx = tiles.get((x, y), (0, 0))
            if mx == 0: gap.append("0"); continue
            if (mn, mx) not in clsidx: clsidx[(mn, mx)] = len(cls); cls.append((mn, mx))
            gap.append(chr(ord("a") + clsidx[(mn, mx)]))
    assert len(cls) <= 25
    classes = " ".join(f"{a} {b}" for a, b in cls)
    drag = ";".join(" ".join(map(str, d)) for d in dragons)
    out.append((name, W, H, sym, edges, " ".join(map(str, portals)), "".join(gap), classes, drag, os.path.relpath(f, R)))
with open(R + "/lineages/g2/bot/mapdb.hpp", "w") as g:
    g.write("// generated by tools/genmaps.py from public map files; do not edit\n#pragma once\n")
    g.write("struct MapInfo { const char *name; int W, H, sym; const char *edges, *portals, *gap, *classes, *dragons; };\n")
    g.write("static const MapInfo MAPDB[] = {\n")
    for name, W, H, sy, e, p, gp, c, d, src in out:
        g.write(f'  // {src}\n  {{"{name}", {W}, {H}, {sy},\n   "{e}",\n   "{p}",\n   "{gp}",\n   "{c}",\n   "{d}"}},\n')
    g.write("};\nstatic const int MAPDB_N = sizeof(MAPDB) / sizeof(MAPDB[0]);\n")
for o in out: print(o[0], o[1], o[2], o[3], o[9])
print(len(out), "maps", os.path.getsize(R + "/lineages/g2/bot/mapdb.hpp"), "bytes")
