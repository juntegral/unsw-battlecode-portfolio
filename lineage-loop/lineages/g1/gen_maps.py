import math
import glob,hashlib,os
files=sorted(glob.glob('../../maps/online-20260927/*.map'))+sorted(glob.glob('maps/*.map'))
seen=set();out=[]
for f in files:
  txt=open(f).read()
  L=[l.split() for l in txt.split('\n') if l.strip()]
  W=H=0;E={};T={};SY='?'
  for p in L:
    if p[0]=='MAP': W,H=int(p[1]),int(p[2])
    elif p[0]=='SYMMETRY': SY=p[1]
    elif p[0]=='EDGE': E[int(p[1])]=(int(p[2]),int(p[3]))
    elif p[0]=='TILE': T[(int(p[1]),int(p[2]))]=(int(p[3]),int(p[4]))
  # canonical per-tile north (h) and west (v) edges: 'o','w', or portal id
  h=[];v=[]
  def g(i): return E.get(i,(0,-1))
  for y in range(H):
    for x in range(W):
      a=g((2*y)*(W+1)+x); b=g((2*((y)%H if y else H))*(W+1)+x) if y==0 else a
      if y==0: b=g((2*H)*(W+1)+x)
      k=a if a[0]!=0 else b
      h.append(k)
      a=g((2*y+1)*(W+1)+x); b=g((2*y+1)*(W+1)+W) if x==0 else a
      k=a if a[0]!=0 else b
      v.append(k)
  key=hashlib.md5(repr((W,H,h,v)).encode()).hexdigest()
  if key in seen: continue
  seen.add(key)
  def enc(lst):
    s=[];ports=[]
    for k,pid in lst:
      if k==1: s.append('w')
      elif k==2: s.append('p'); ports.append(pid)
      else: s.append('.')
    return ''.join(s),ports
  hs,hp=enc(h); vs,vp=enc(v)
  # tile rate class: '0' never, else chr(ord('a')+min(25, avg gap//4))
  ts=[]
  for y in range(H):
    for x in range(W):
      mn,mx=T.get((x,y),(0,0))
      if mx==0: ts.append('0')
      else: ts.append(chr(ord('a')+min(25,max(0,round(math.log2(max(1,(mn+mx)/2))*3)))))
  out.append((os.path.basename(f),W,H,hs,hp,vs,vp,''.join(ts),SY))
with open('bot/maps_data.hpp','w') as o:
  o.write('// generated by gen_maps.py from public map files\n#pragma once\nstruct KnownMap { const char* name; int w, h; const char* he; const int* hp; int nhp; const char* ve; const int* vp; int nvp; const char* tiles; const char* sym; };\n')
  for i,(n,W,H,hs,hp,vs,vp,ts,SY) in enumerate(out):
    o.write('static const int KM%d_hp[] = {%s};\nstatic const int KM%d_vp[] = {%s};\n'%(i,','.join(map(str,hp)) or '0',i,','.join(map(str,vp)) or '0'))
  o.write('static const KnownMap KNOWN_MAPS[] = {\n')
  for i,(n,W,H,hs,hp,vs,vp,ts,SY) in enumerate(out):
    o.write(' {"%s",%d,%d,"%s",KM%d_hp,%d,"%s",KM%d_vp,%d,"%s","%s"},\n'%(n,W,H,hs,i,len(hp),vs,i,len(vp),ts,SY))
  o.write('};\nstatic const int NUM_KNOWN_MAPS = %d;\n'%len(out))
print([x[0] for x in out])
