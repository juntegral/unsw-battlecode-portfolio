#!/usr/bin/env node
'use strict';
// genfrontdb.js — writes frontdb.hpp for unsw-swarm v1.1 (frontier allocation, versions/v1.1/VERSION.md): the frontier bin of every tile of
// every table map of mapdb.hpp (same order), from each file team's point of view, exactly as the spatial study defines it
// (exp/spatial/lib.js geometry(): movement distance from all of a team's initial body segments over kelp, portals and wrap;
// f = d_own / (d_own + d_enemy); own unreachable 1, enemy unreachable 0, both zero .5; bin = min(4, floor(5 f)); both unreachable = 5).
// Read from one local replay per table map (the replay carries the map's portals and starting dragons as the judge built them), and checked:
//   - both seats of one map give the same table;
//   - terrdb.hpp agrees: '1' (file team A nearer) <=> f_A < .5, '2' <=> f_A > .5, '0' <=> equal or unreachable;
//   - a and b layouts of a family agree (same geometry and starting bodies; Prisoners Dilemma 10 differs and is listed).
// Two strings per map: side '1' (terrdb's team A, f_A bins) then side '2' (f_B bins). One char per tile: '0'-'4' the bin, '5' unreachable.
// usage (repository root): node exp/v11/genfrontdb.js versions/v1.1/bot/frontdb.hpp
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const out = process.argv[2];
if (!out) { console.error('usage: genfrontdb.js <out frontdb.hpp>'); process.exit(2); }
const { makeLoader, viewerSource } = require(path.join(ROOT, 'tools', 'top_features.js'));
const load = makeLoader(viewerSource());
const { geometry } = require(path.join(ROOT, 'exp', 'spatial', 'lib.js'));
// mapdb.hpp order (legacy exp/mapid/genmapdb.js): maps/online-20260927 by file name, then prisoners_dilemma_10 and the four *_b maps
const A = fs.readdirSync(path.join(ROOT, 'maps', 'online-20260927')).filter(x => x.endsWith('.map')).sort().map(f => f.replace(/\.map$/, ''));
const KEYS = [...A, 'prisoners_dilemma_10', 'devil_b', 'queen_of_spades_b', 'schooltime_b', 'slithery_fight_b'];
const dbSrc = fs.readFileSync(path.join(ROOT, 'versions', 'v1.1', 'bot', 'mapdb.hpp'), 'utf8');
const dims = [...dbSrc.matchAll(/\{"([^"]+)", (\d+), (\d+),/g)].map(m => ({ name: m[1], W: +m[2], H: +m[3] }));
if (dims.length !== KEYS.length) throw new Error(`mapdb has ${dims.length} maps, expected ${KEYS.length}`);
const terrSrc = fs.readFileSync(path.join(ROOT, 'versions', 'v1.1', 'bot', 'terrdb.hpp'), 'utf8');
const TERR = [...terrSrc.matchAll(/^\s*"([012]+)",/gm)].map(m => m[1]);
if (TERR.length !== KEYS.length) throw new Error(`terrdb has ${TERR.length} maps, expected ${KEYS.length}`);
function replayOf(key, seat) {
  const b = /_(b|10)$/.test(key);
  const sets = b ? ['k8-b-px4', 'v1-b-px4', 'v0t-b-px4'] : ['v1final-a-px4', 'v1-a-px4', 'v0t-a-px4'];
  for (const s of sets) for (const opp of ['proxy4_king', 'proxy4_elim', 'proxy4_swarm']) {
    const f = path.join(ROOT, 'exp', 'v1', s, 'games', `${opp}_${key}_${seat}_${b ? 2 : 1}`, 'game.replay');
    if (fs.existsSync(f)) return f;
  }
  throw new Error('no local replay for ' + key + ' ' + seat);
}
function binsOf(file) {
  const R = load(file), M = R.match.map;
  const g = geometry(M, 'x', '?');
  return { W: M.width, H: M.height, A: g.bin.A.join(''), B: g.bin.B.join(''), fA: g.f.A };
}
const rows = [];
for (const [i, key] of KEYS.entries()) {
  const a = binsOf(replayOf(key, 'A')), b = binsOf(replayOf(key, 'B'));
  if (a.A !== b.A || a.B !== b.B) throw new Error('seats disagree on ' + key);
  if (a.W !== dims[i].W || a.H !== dims[i].H) throw new Error(`size mismatch ${key}: replay ${a.W}x${a.H}, mapdb ${dims[i].name} ${dims[i].W}x${dims[i].H}`);
  const T = TERR[i];
  let bad = 0;
  for (let k = 0; k < T.length; k++) {
    const f = a.fA[k], want = f === null ? '0' : f < 0.5 ? '1' : f > 0.5 ? '2' : '0';
    if (T[k] !== want) bad++;
  }
  if (bad) throw new Error(`terrdb disagrees with f_A on ${bad} tiles of ${key}`);
  rows.push({ key, name: dims[i].name, W: a.W, H: a.H, A: a.A, B: a.B });
  const hist = s => [0, 1, 2, 3, 4, 5].map(c => s.split('').filter(x => x === String(c)).length).join('/');
  console.log(`  ${i} ${dims[i].name} ${key} ${a.W}x${a.H}: side 1 bins ${hist(a.A)}  side 2 bins ${hist(a.B)}  terrdb agrees`);
}
for (const [k, fam] of [['devil_b', 'devil'], ['queen_of_spades_b', 'queen_of_spades'], ['schooltime_b', 'schooltime'], ['slithery_fight_b', 'slithery_fight'], ['prisoners_dilemma_10', 'prisoners_dilemma']]) {
  const x = rows.find(r => r.key === k), y = rows.find(r => r.key === fam);
  console.log(`  ${k} vs ${fam}: ${x.A === y.A && x.B === y.B ? 'same bins' : 'different bins (' + x.A.split('').filter((c, i) => c !== y.A[i]).length + ' tiles)'}`);
}
let s = '// frontdb.hpp — generated by exp/v11/genfrontdb.js from one local replay per table map of mapdb.hpp (same order). Do not edit.\n';
s += '// unsw-swarm v1.1 frontier allocation: the frontier bin of each tile as the spatial study defines it (exp/spatial/lib.js geometry()):\n';
s += '// f = d_own / (d_own + d_enemy), movement distance from all of a team\'s initial body segments (kelp, portals, wrap); own unreachable 1,\n';
s += '// enemy unreachable 0, both zero .5; bin = min(4, floor(5 f)) from own-deep 0 to enemy-deep 4; both unreachable 5. Two strings per map:\n';
s += '// FRONT[2 m] from terrdb side \'1\' (the file\'s team A), FRONT[2 m + 1] from side \'2\'. One char per tile (row-major).\n';
s += '#pragma once\nnamespace seed0 { namespace frontdb {\nstatic const char* const FRONT[] = {\n';
for (const r of rows) s += `  "${r.A}", // ${r.name} (${r.key}) side 1\n  "${r.B}", // ${r.name} (${r.key}) side 2\n`;
s += '};\n}} // namespace seed0::frontdb\n';
fs.writeFileSync(out, s);
console.log('wrote', out, (s.length / 1024).toFixed(1) + ' KB');
