#!/usr/bin/env node
'use strict';
// genmapstart.js (W2, v1.6.1): writes mapstart.hpp, the start dragons of every table map, for the start anchor of the recognition gate
// (World::updateMapId). Same files and order as mapdb.hpp (legacy/exp/mapid/genmapdb.js: maps/online-20260927 in name order, then
// maps/variants/prisoners_dilemma_10.map and the four *_b.map). Per map: its DRAGON lines in file order (ids are assigned in file order,
// rules/map-files.md): head x, y and segment count. Checks the names and sizes against the mapdb.hpp it is given.
// usage (repository root): node exp/w2/genmapstart.js versions/v1.6.1/bot/mapdb.hpp versions/v1.6.1/bot/mapstart.hpp
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const [dbFile, out] = process.argv.slice(2);
if (!dbFile || !out) { console.error('usage: genmapstart.js <mapdb.hpp> <out mapstart.hpp>'); process.exit(2); }
const files = fs.readdirSync(path.join(ROOT, 'maps', 'online-20260927')).filter(f => f.endsWith('.map')).sort().map(f => path.join(ROOT, 'maps', 'online-20260927', f));
files.push(path.join(ROOT, 'maps', 'variants', 'prisoners_dilemma_10.map'));
for (const f of ['devil_b', 'queen_of_spades_b', 'schooltime_b', 'slithery_fight_b']) files.push(path.join(ROOT, 'maps', 'variants', f + '.map'));
const maps = files.map(file => {
  let W = 0, H = 0, name = path.basename(file, '.map'); const d = [];
  for (const l of fs.readFileSync(file, 'utf8').split('\n').map(s => s.trim()).filter(Boolean)) {
    const t = l.split(/\s+/);
    if (t[0] === 'MAP') { W = +t[1]; H = +t[2]; }
    else if (t[0] === 'MAP_NAME') name = l.slice(9).trim();
    else if (t[0] === 'DRAGON') d.push([+t[3], +t[4], +t[2]]);
  }
  return { file: path.relative(ROOT, file), name: name.replace(/ /g, '_'), W, H, d };
});
// mapdb.hpp entries: {"Name", W, H,
const db = [...fs.readFileSync(dbFile, 'utf8').matchAll(/^  \{"([^"]+)", (\d+), (\d+),$/gm)].map(m => ({ name: m[1], W: +m[2], H: +m[3] }));
if (db.length !== maps.length) throw new Error(`mapdb.hpp has ${db.length} maps, the files ${maps.length}`);
maps.forEach((m, i) => { if (db[i].name !== m.name || db[i].W !== m.W || db[i].H !== m.H) throw new Error(`entry ${i}: mapdb ${db[i].name} ${db[i].W}x${db[i].H} vs file ${m.name} ${m.W}x${m.H}`); });
let s = '// mapstart.hpp — generated by exp/w2/genmapstart.js from the files mapdb.hpp was built from, in the same order. Do not edit.\n';
s += '// v1.6.1 (W2) start anchor of the recognition gate (mapid.cpp): per table map, its dragons in file order (the game assigns ids in\n';
s += '// file order, rules/map-files.md): head x, y and segment count.\n';
s += '#pragma once\n#include "mapdb.hpp"\nnamespace seed0 { namespace mapstart {\n';
s += 'struct Start { short x, y, len; };\nstruct MapStarts { int n; const Start* d; };\n';
maps.forEach((m, i) => { s += `static const Start S${i}[] = {${m.d.map(q => `{${q[0]}, ${q[1]}, ${q[2]}}`).join(', ')}};   // ${m.name}\n`; });
s += 'static const MapStarts STARTS[] = {' + maps.map((m, i) => `{${m.d.length}, S${i}}`).join(', ') + '};\n';
s += 'static_assert(sizeof(STARTS) / sizeof(STARTS[0]) == mapdb::COUNT, "mapstart.hpp and mapdb.hpp list the same maps");\n';
s += '}} // namespace seed0::mapstart\n';
fs.writeFileSync(out, s);
console.log('wrote', out);
maps.forEach((m, i) => console.log(`  ${i} ${m.name} ${m.W}x${m.H} dragons ${m.d.length}  <- ${m.file}`));
