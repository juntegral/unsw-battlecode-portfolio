#!/usr/bin/env node
// v1.4 opening module: generates versions/v1.4/bot/opdb.hpp from the Codex opening study (exp/opening/scripts.json, research/observations/
// opening-book.md §11). One script per map / layout / physical side: the selected winner cluster's medoid game, as the study chose it.
//   roles: the start dragons (roots, by start head and length) and the children born in round 0 (by birth head and length; a child is a new
//          process and knows only its own birth), with their split schedule up to SPLIT_END (child length per split) and their waypoints (the
//          medoid's head at r5 / r10 / r15 / r20 / r25, up to the script's end) when the script pulls.
//   per map (MAPS below): the script's last round, whether it pulls to waypoints, whether the loss of a dragon of ours ends it.
// usage: node exp/v14/genopdb.js  (writes versions/v1.4/bot/opdb.hpp and exp/v14/opdb.json)
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const S = JSON.parse(fs.readFileSync(path.join(ROOT, 'exp/opening/scripts.json'), 'utf8'));
// fam = mapdb.hpp family name; endR = the script's last round; splitEnd = scripted splits up to this round; pull = follow the waypoints;
// lossStops = a dragon of ours lost ends the script (not on Slithery Fight, where the elite's early children die by the dozen)
const SIZE = { Devil: [32, 16], Trophy: [25, 25], Schooltime: [60, 40], Slithery_Fight: [63, 27], Default: [32, 32] };
const MAPS = [
  { key: 'Devil/a', fam: 'Devil', layout: 'a', endR: 25, splitEnd: 10, pull: true, lossStops: true },
  { key: 'Devil/b', fam: 'Devil', layout: 'b', endR: 25, splitEnd: 10, pull: true, lossStops: true },
  { key: 'Trophy/a', fam: 'Trophy', layout: 'a', endR: 25, splitEnd: 10, pull: true, lossStops: true },
  { key: 'Schooltime/a', fam: 'Schooltime', layout: 'a', endR: 25, splitEnd: 10, pull: true, lossStops: true },
  { key: 'Schooltime/b', fam: 'Schooltime', layout: 'b', endR: 25, splitEnd: 10, pull: true, lossStops: true },
  { key: 'Slithery Fight/a', fam: 'Slithery_Fight', layout: 'a', endR: 10, splitEnd: 10, pull: false, lossStops: false },
  { key: 'Slithery Fight/b', fam: 'Slithery_Fight', layout: 'b', endR: 10, splitEnd: 10, pull: false, lossStops: false },
  { key: 'Default/a', fam: 'Default', layout: 'a', endR: 1, splitEnd: 0, pull: false, lossStops: true },
];
const WP_ROUNDS = [5, 10, 15, 20, 25, 35, 50];
const MAX_SPLIT = 12, MAX_WP = 6;
const out = [], json = [];
out.push('// opdb.hpp — generated by exp/v14/genopdb.js from exp/opening/scripts.json (Codex opening study, research/observations/opening-book.md §11).');
out.push('// Do not edit. The v1.4 opening module (opmod.cpp) reads it. One script per map / layout / physical side (the file\'s DRAGON 0 side is A):');
out.push('// the selected winner cluster\'s medoid game. Roles: start dragons (born 0 at their start head) and the children born in round 0 (birth head');
out.push('// and length), each with its split schedule (round, child length) and, where the script pulls, its head at r5 / r10 / r15 / r20 / r25.');
out.push('#pragma once');
out.push('#include <cstdint>');
out.push('namespace seed0 { namespace opdb {');
out.push(`struct Split { int16_t r; int8_t child; };`);
out.push(`struct Wp { int16_t r, x, y; };`);
out.push(`struct Role { const char* label; int16_t born, x, y; int8_t len; int8_t nSplit; Split split[${MAX_SPLIT}]; int8_t nWp; Wp wp[${MAX_WP}]; };`);
out.push(`struct Script { const char* fam; char layout; char side; int16_t endR; bool pull; bool lossStops; int8_t nRoles; const Role* roles; const char* src; };`);
const scriptRows = [];
for (const m of MAPS) for (const side of ['A', 'B']) {
  const v = Object.assign({ W: SIZE[m.fam][0], H: SIZE[m.fam][1] }, S[m.key][side]);
  const roles = [];
  const byLabel = new Map(v.children.map(c => [c.label, c]));
  const cands = v.children.filter(c => c.born === 0);   // roots and round-0 children
  for (const c of cands) {
    const splits = v.splitSchedule.filter(sp => sp.parentLabel === c.label && sp.r <= m.splitEnd).map(sp => ({ r: sp.r, child: sp.childLength }));
    let wps = [];
    if (m.pull) {
      wps = (c.waypoints || []).filter(w => WP_ROUNDS.includes(w.r) && w.r > c.born && w.r <= m.endR).map(w => ({ r: w.r, x: w.xy[0], y: w.xy[1] }));
      // a head moves one tile a round (a sprint costs a segment): a waypoint farther (wrapped Manhattan) from the previous one than the rounds
      // between them was reached through a portal; the pull stops before it (the search only routes over portals this process has seen)
      let px = c.birthHead[0], py = c.birthHead[1], pr = c.born;
      for (let i = 0; i < wps.length; i++) {
        const w = wps[i], dx = Math.abs(w.x - px), dy = Math.abs(w.y - py);
        const d = Math.min(dx, v.W - dx) + Math.min(dy, v.H - dy);
        if (d > w.r - pr + 1) { wps = wps.slice(0, i); break; }
        px = w.x; py = w.y; pr = w.r;
      }
    }
    // a role that neither splits nor pulls in this script has nothing to follow
    if (!splits.length && !wps.length) continue;
    if (splits.length > MAX_SPLIT || wps.length > MAX_WP) throw new Error(`${m.key} ${side} ${c.label}: too many events`);
    roles.push({ label: c.label, born: c.born, x: c.birthHead[0], y: c.birthHead[1], len: c.birthLength, splits, wps });
  }
  const id = `${m.fam.toUpperCase()}_${m.layout.toUpperCase()}_${side}`;
  out.push(`// ${m.key} side ${side}: medoid ${v.key} (team ${v.team}), cluster ${v.clusterId}, ${v.clusterWinnerN} winners of that side in the cluster`);
  out.push(`static const Role ${id}[] = {`);
  for (const r of roles) {
    const sp = r.splits.map(s => `{${s.r}, ${s.child}}`).join(', ');
    const wp = r.wps.map(w => `{${w.r}, ${w.x}, ${w.y}}`).join(', ');
    out.push(`  {"${r.label}", ${r.born}, ${r.x}, ${r.y}, ${r.len}, ${r.splits.length}, {${sp}}, ${r.wps.length}, {${wp}}},`);
  }
  out.push('};');
  scriptRows.push(`  {"${m.fam}", '${m.layout}', '${side}', ${m.endR}, ${m.pull}, ${m.lossStops}, ${roles.length}, ${id}, "${v.key}"},`);
  json.push({ key: m.key, fam: m.fam, layout: m.layout, side, endR: m.endR, pull: m.pull, lossStops: m.lossStops, medoid: v.key, roles, targets: v.targets });
}
out.push('static const Script SCRIPTS[] = {');
out.push(...scriptRows);
out.push('};');
out.push(`constexpr int COUNT = ${scriptRows.length};`);
out.push('}} // namespace seed0::opdb');
fs.writeFileSync(path.join(ROOT, 'versions/v1.4/bot/opdb.hpp'), out.join('\n') + '\n');
fs.writeFileSync(path.join(ROOT, 'exp/v14/opdb.json'), JSON.stringify(json, null, 1));
console.log('scripts', scriptRows.length, 'roles', json.reduce((a, s) => a + s.roles.length, 0));
