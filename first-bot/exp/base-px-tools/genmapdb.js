#!/usr/bin/env node
// Generates mapdb.hpp (kelp, portals and pearl spawn ranges of the known maps) for the base-px bots.
// usage: node exp/base-px-tools/genmapdb.js <out mapdb.hpp> [map dir ...]   (default: maps/online-20260927)
// Map file format: rules/map-files.md. Edge index = r*(W+1)+c; even r = 2y: north side of tile (c,y); odd r = 2y+1: west
// side of tile (c,y). The board wraps, so the files list W*H of each kind. Checked against replay map data (0 mismatches).
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const out = process.argv[2];
const dirs = process.argv.slice(3).length ? process.argv.slice(3) : [path.join(ROOT, 'maps', 'online-20260927')];
const maps = [];
for (const d of dirs) for (const f of fs.readdirSync(d).filter(x => x.endsWith('.map')).sort()) maps.push(path.join(d, f));
function parse(file) {
  const L = fs.readFileSync(file, 'utf8').split('\n').map(s => s.trim()).filter(Boolean);
  let W = 0, H = 0, name = path.basename(file, '.map'), sym = -1;
  const tiles = [], edges = [], heads = [];
  for (const l of L) {
    const t = l.split(/\s+/);
    if (t[0] === 'MAP') { W = +t[1]; H = +t[2]; }
    else if (t[0] === 'MAP_NAME') name = l.slice(9).trim();
    else if (t[0] === 'SYMMETRY') sym = t[1] === 'xy' ? 2 : t[1] === 'y' ? 1 : t[1] === 'x' ? 0 : -1; // bot codes: 0 flip y, 1 flip x, 2 rotate 180
    else if (t[0] === 'TILE') tiles.push([+t[1], +t[2], +t[3], +t[4]]);
    else if (t[0] === 'EDGE') edges.push([+t[1], +t[2], +t[3]]);
    else if (t[0] === 'DRAGON') heads.push([+t[1], +t[3], +t[4]]); // team, head x, head y
  }
  const hk = new Uint8Array(W * H), vk = new Uint8Array(W * H);
  const portal = new Map(); // id -> ends
  for (const [i, kind, pid] of edges) {
    const r = Math.floor(i / (W + 1)), c = i % (W + 1);
    let x, y, side;
    if (r % 2 === 0) { y = (r / 2) % H; x = c % W; side = 0; } else { y = (r - 1) / 2; x = c % W; side = 1; }
    if (kind === 1) { if (side === 0) hk[y * W + x] = 1; else vk[y * W + x] = 1; }
    else if (kind === 2) { if (!portal.has(pid)) portal.set(pid, []); const e = portal.get(pid); if (!e.some(q => q[0] === x && q[1] === y && q[2] === side)) e.push([x, y, side]); }
  }
  const pal = [], palIdx = new Map(), sp = new Array(W * H).fill(0);
  const key0 = '0,0'; pal.push([0, 0]); palIdx.set(key0, 0);
  for (const [x, y, mn, mx] of tiles) { const k = mn + ',' + mx; if (!palIdx.has(k)) { palIdx.set(k, pal.length); pal.push([mn, mx]); } sp[y * W + x] = palIdx.get(k); }
  if (pal.length > 60) throw new Error('palette too large ' + file);
  const hex = a => { let s = ''; for (let i = 0; i < a.length; i += 4) { let v = 0; for (let b = 0; b < 4; b++) if (i + b < a.length && a[i + b]) v |= 1 << b; s += v.toString(16); } return s; };
  const ports = [];
  for (const [pid, e] of [...portal.entries()].sort((a, b) => a[0] - b[0])) { if (e.length !== 2) throw new Error('portal ' + pid + ' has ' + e.length + ' ends in ' + file); ports.push(...e[0], ...e[1]); }
  return { name, W, H, sym, hk: hex(hk), vk: hex(vk), ports, pal, sp: sp.map(i => String.fromCharCode(48 + i)).join(''), heads };
}
const P = maps.map(parse);
let s = '// mapdb.hpp — generated by exp/base-px-tools/genmapdb.js from ' + dirs.map(d => path.relative(ROOT, d)).join(', ') + '. Do not edit.\n';
s += '// Per map: size, kelp bitsets (hex, 4 tiles per digit, bit b = tile i+b; hk = north side, vk = west side), portal pairs\n';
s += '// (x, y, side 0=N 1=W, x, y, side), pearl spawn ranges (palette of min,max; one char per tile, 48 + palette index),\n';
s += '// symmetry as the bot codes it (0 flip y, 1 flip x, 2 rotate 180; file SYMMETRY x / y / xy), initial dragon heads\n';
s += '// (team 0=A 1=B, x, y).\n';
s += '#pragma once\nnamespace mapdb {\nstruct MapInfo { const char* name; int W, H, sym; const char* hk; const char* vk; int nPortals; const int* portals; int nPal; const int* pal; const char* spawn; int nHeads; const int* heads; };\n';
P.forEach((m, i) => {
  s += `static const int P${i}[] = {${m.ports.length ? m.ports.join(',') : '0'}};\n`;
  s += `static const int S${i}[] = {${m.pal.map(q => q.join(',')).join(',')}};\n`;
  s += `static const int D${i}[] = {${m.heads.map(q => q.join(',')).join(',')}};\n`;
});
s += 'static const MapInfo MAPS[] = {\n';
P.forEach((m, i) => {
  s += `  {"${m.name}", ${m.W}, ${m.H}, ${m.sym},\n   "${m.hk}",\n   "${m.vk}",\n   ${m.ports.length / 6}, P${i}, ${m.pal.length}, S${i},\n   "${m.sp}", ${m.heads.length}, D${i}},\n`;
});
s += '};\nconstexpr int COUNT = ' + P.length + ';\n}\n';
fs.writeFileSync(out, s);
console.log('wrote', out, P.map(m => `${m.name} ${m.W}x${m.H} portals ${m.ports.length / 6} palette ${m.pal.length}`).join('; '), (s.length / 1024).toFixed(1) + ' KB');
