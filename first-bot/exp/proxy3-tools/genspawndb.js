#!/usr/bin/env node
// Generates spawndb.hpp for the proxy3 bots: per known map its size, kelp and portal edges (to recognise the map from
// what a dragon sees) and the pearl spawn range of every tile (palette of min,max gaps; one char per tile = 48 + index).
// The proxies use it only for pearl expectations (where and how often pearls appear); board geometry is still learned
// from vision. Maps: maps/online-20260927 and the server's 10-dragon Prisoners Dilemma (maps/variants).
// usage: node exp/proxy3-tools/genspawndb.js <out spawndb.hpp>
// Edge index = r*(W+1)+c; even r = 2y: north side of tile (c,y); odd r = 2y+1: west side of tile (c,y) (as in
// exp/base-px-tools/genmapdb.js, checked there against replay map data).
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const out = process.argv[2];
if (!out) { console.error('usage: genspawndb.js <out>'); process.exit(2); }
const files = [];
for (const f of fs.readdirSync(path.join(ROOT, 'maps', 'online-20260927')).filter(x => x.endsWith('.map')).sort()) files.push(path.join(ROOT, 'maps', 'online-20260927', f));
files.push(path.join(ROOT, 'maps', 'variants', 'prisoners_dilemma_10.map'));
function parse(file) {
  const L = fs.readFileSync(file, 'utf8').split('\n').map(s => s.trim()).filter(Boolean);
  let W = 0, H = 0, name = path.basename(file, '.map');
  const tiles = [], edges = [];
  for (const l of L) {
    const t = l.split(/\s+/);
    if (t[0] === 'MAP') { W = +t[1]; H = +t[2]; }
    else if (t[0] === 'MAP_NAME') name = l.slice(9).trim();
    else if (t[0] === 'TILE') tiles.push([+t[1], +t[2], +t[3], +t[4]]);
    else if (t[0] === 'EDGE') edges.push([+t[1], +t[2], +t[3]]);
  }
  if (/prisoners_dilemma_10/.test(file)) name = 'Prisoners Dilemma 10';
  const hk = new Uint8Array(W * H), vk = new Uint8Array(W * H), hp = new Uint8Array(W * H), vp = new Uint8Array(W * H);
  for (const [i, kind] of edges) {
    const r = Math.floor(i / (W + 1)), c = i % (W + 1);
    let x, y, side;
    if (r % 2 === 0) { y = (r / 2) % H; x = c % W; side = 0; } else { y = (r - 1) / 2; x = c % W; side = 1; }
    const k = y * W + x;
    if (kind === 1) { if (side === 0) hk[k] = 1; else vk[k] = 1; }
    else if (kind === 2) { if (side === 0) hp[k] = 1; else vp[k] = 1; }
  }
  const pal = [[0, 0]], palIdx = new Map([['0,0', 0]]), sp = new Array(W * H).fill(0);
  for (const [x, y, mn, mx] of tiles) { const key = mn + ',' + mx; if (!palIdx.has(key)) { palIdx.set(key, pal.length); pal.push([mn, mx]); } sp[y * W + x] = palIdx.get(key); }
  if (pal.length > 60) throw new Error('palette too large ' + file);
  const hex = a => { let s = ''; for (let i = 0; i < a.length; i += 4) { let v = 0; for (let b = 0; b < 4; b++) if (i + b < a.length && a[i + b]) v |= 1 << b; s += v.toString(16); } return s; };
  return { name, W, H, hk: hex(hk), vk: hex(vk), hp: hex(hp), vp: hex(vp), pal, sp: sp.map(i => String.fromCharCode(48 + i)).join('') };
}
const P = files.map(parse);
let s = '// spawndb.hpp — generated by exp/proxy3-tools/genspawndb.js from maps/online-20260927 and maps/variants/prisoners_dilemma_10.map.\n';
s += '// Do not edit. Per map: size; kelp (hk north side, vk west side) and portal (hp, vp) edge bitsets (hex, 4 tiles per digit,\n';
s += '// bit b = tile i+b); pearl spawn ranges (palette of min,max gaps; one char per tile = 48 + palette index; 0 = never).\n';
s += '#pragma once\nnamespace spawndb {\nstruct MapInfo { const char* name; int W, H; const char* hk; const char* vk; const char* hp; const char* vp; int nPal; const int* pal; const char* spawn; };\n';
P.forEach((m, i) => { s += `static const int S${i}[] = {${m.pal.map(q => q.join(',')).join(',')}};\n`; });
s += 'static const MapInfo MAPS[] = {\n';
P.forEach((m, i) => { s += `  {"${m.name}", ${m.W}, ${m.H},\n   "${m.hk}",\n   "${m.vk}",\n   "${m.hp}",\n   "${m.vp}",\n   ${m.pal.length}, S${i},\n   "${m.sp}"},\n`; });
s += '};\nconstexpr int COUNT = ' + P.length + ';\n}\n';
fs.writeFileSync(out, s);
console.log('wrote', out, P.map(m => `${m.name} ${m.W}x${m.H} palette ${m.pal.length}`).join('; '), (s.length / 1024).toFixed(1) + ' KB');
