#!/usr/bin/env node
'use strict';
// genmapdb.js — writes mapdb.hpp for the cand-mapid bot (exp/cand-mapid/bot): the map table its dragons use to recognise
// the map and the pearl layout at round 0 (hypothesis #11, research/experiments/cand-mapid.md).
// Same table as the proxy4 bots (exp/proxy4-tools/genspawndb.js: maps/online-20260927 in name order, then
// maps/variants/prisoners_dilemma_10.map and the four *_b.map), with three differences:
//   - Prisoners Dilemma 10 joins the Prisoners Dilemma family as its layout b (the proxies keep it apart; for recognition
//     only, the family's countdown check separates the two: the middle tiles are 480-490 in a and 1-100 in b);
//   - layout: 'a' for the online file, 'b' for the second layout (PD: the 10-dragon version);
//   - elim: the map family usually ends by elimination (Default, Devil, Prisoners Dilemma, Queen Of Spades, Trophy;
//     research/observations/top-summary-2026-09-29.md 2), else it is a round-500 map.
// Per map: size; kelp (hk north side, vk west side) and portal (hp, vp) edge bitsets (hex, 4 tiles per digit, bit b = tile
// i+b); pearl spawn ranges (palette of min,max gaps; one char per tile = 48 + palette index; palette 0 = never spawns).
// usage (repository root): node exp/mapid/genmapdb.js exp/cand-mapid/bot/mapdb.hpp
// Edge index = r*(W+1)+c; even r = 2y: north side of tile (c,y); odd r = 2y+1: west side of tile (c,y)
// (exp/base-px-tools/genmapdb.js, checked there against replay map data).
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const out = process.argv[2];
if (!out) { console.error('usage: genmapdb.js <out mapdb.hpp>'); process.exit(2); }
const files = [];
for (const f of fs.readdirSync(path.join(ROOT, 'maps', 'online-20260927')).filter(x => x.endsWith('.map')).sort()) files.push(path.join(ROOT, 'maps', 'online-20260927', f));
files.push(path.join(ROOT, 'maps', 'variants', 'prisoners_dilemma_10.map'));
for (const f of ['devil_b', 'queen_of_spades_b', 'schooltime_b', 'slithery_fight_b']) files.push(path.join(ROOT, 'maps', 'variants', f + '.map'));
const ELIM = new Set(['Default', 'Devil', 'Prisoners Dilemma', 'Queen Of Spades', 'Trophy']);
function parse(file) {
  const L = fs.readFileSync(file, 'utf8').split('\n').map(s => s.trim()).filter(Boolean);
  let W = 0, H = 0, name = path.basename(file, '.map');
  const tiles = [], edges = [];
  for (const l of L) {
    const t = l.split(/\s+/);
    if (t[0] === 'MAP') { W = +t[1]; H = +t[2]; }
    else if (t[0] === 'MAP_NAME') name = l.slice(9).trim();
    else if (t[0] === 'TILE') tiles.push([+t[1], +t[2], +t[3], +t[4]]);
    else if (t[0] === 'EDGE') edges.push([+t[1], +t[2], +t[3]]);
  }
  const isB = /_b\.map$/.test(file) || /prisoners_dilemma_10/.test(file);
  const hk = new Uint8Array(W * H), vk = new Uint8Array(W * H), hp = new Uint8Array(W * H), vp = new Uint8Array(W * H);
  for (const [i, kind] of edges) {
    const r = Math.floor(i / (W + 1)), c = i % (W + 1);
    let x, y, side;
    if (r % 2 === 0) { y = (r / 2) % H; x = c % W; side = 0; } else { y = (r - 1) / 2; x = c % W; side = 1; }
    const k = y * W + x;
    if (kind === 1) { if (side === 0) hk[k] = 1; else vk[k] = 1; }
    else if (kind === 2) { if (side === 0) hp[k] = 1; else vp[k] = 1; }
  }
  const pal = [[0, 0]], palIdx = new Map([['0,0', 0]]), sp = new Array(W * H).fill(0);
  for (const [x, y, mn, mx] of tiles) { const key = mx > 0 ? mn + ',' + mx : '0,0'; if (!palIdx.has(key)) { palIdx.set(key, pal.length); pal.push(key.split(',').map(Number)); } sp[y * W + x] = palIdx.get(key); }
  if (pal.length > 60) throw new Error('palette too large ' + file);
  const hex = a => { let s = ''; for (let i = 0; i < a.length; i += 4) { let v = 0; for (let b = 0; b < 4; b++) if (i + b < a.length && a[i + b]) v |= 1 << b; s += v.toString(16); } return s; };
  return { file: path.relative(ROOT, file), name, isB, W, H, hk: hex(hk), vk: hex(vk), hp: hex(hp), vp: hex(vp), pal, sp: sp.map(i => String.fromCharCode(48 + i)).join('') };
}
const P = files.map(parse);
P.forEach((m, i) => {
  m.fam = i;
  if (!m.isB) return;
  m.fam = P.findIndex(o => !o.isB && o.name === m.name);
  const a = P[m.fam];
  if (m.fam < 0 || !(a.W === m.W && a.H === m.H && a.hk === m.hk && a.vk === m.vk && a.hp === m.hp && a.vp === m.vp)) throw new Error('b layout without an a map of the same geometry: ' + m.file);
});
let s = '// mapdb.hpp — generated by exp/mapid/genmapdb.js from maps/online-20260927 (layout a) and maps/variants\n';
s += '// (prisoners_dilemma_10 and the four *_b.map: layout b). Do not edit.\n';
s += '// Per map: size; kelp (hk north side, vk west side) and portal (hp, vp) edge bitsets (hex, 4 tiles per digit, bit b = tile\n';
s += '// i+b); pearl spawn ranges (palette of min,max gaps; one char per tile = 48 + palette index; palette 0 = never spawns);\n';
s += '// fam = index of the family\'s a map (a and b share size and edges and differ only in pearls); layout a/b; elim = the family\n';
s += '// usually ends by elimination (else a round-500 map). Recognition: World::updateMapId (mapid.cpp).\n';
s += '#pragma once\nnamespace seed0 { namespace mapdb {\n';
s += 'struct MapInfo { const char* name; int W, H; const char* hk; const char* vk; const char* hp; const char* vp; int nPal; const int* pal; const char* spawn; int fam; char layout; bool elim; };\n';
P.forEach((m, i) => { s += `static const int PAL${i}[] = {${m.pal.map(q => q.join(',')).join(',')}};\n`; });
s += 'static const MapInfo MAPS[] = {\n';
P.forEach((m, i) => { s += `  {"${m.name.replace(/ /g, '_')}", ${m.W}, ${m.H},\n   "${m.hk}",\n   "${m.vk}",\n   "${m.hp}",\n   "${m.vp}",\n   ${m.pal.length}, PAL${i},\n   "${m.sp}", ${m.fam}, '${m.isB ? 'b' : 'a'}', ${ELIM.has(m.name) ? 'true' : 'false'}},\n`; });
s += '};\nconstexpr int COUNT = ' + P.length + ';\n}} // namespace seed0::mapdb\n';
fs.writeFileSync(out, s);
console.log('wrote', out, (s.length / 1024).toFixed(1) + ' KB');
for (const [i, m] of P.entries()) console.log(`  ${i} ${m.name}${m.isB ? ' (b)' : ''} ${m.W}x${m.H} palette ${m.pal.map(q => q.join('-')).join(' ')} fam ${m.fam} ${ELIM.has(m.name) ? 'elim' : 'r500'}  <- ${m.file}`);
