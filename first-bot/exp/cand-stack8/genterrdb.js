#!/usr/bin/env node
'use strict';
// genterrdb.js — writes terrdb.hpp for the cand-stack8 bot (F2, research/experiments/cand-stack8.md): the territory of every
// table map of mapdb.hpp (same order), as the mass ledger defines it and tools/mech_check.js measures F's designed situation:
// a tile belongs to the team whose starting bodies are nearer by movement distance (kelp, portals, wrap); equal or unreachable =
// neutral (tools/mass_ledger.js perGame ctx.terr). Read from one local replay per table map (the replay carries the map's
// portals and starting dragons exactly as the judge built them), and checked: a and b layouts of a family agree except the
// 10-dragon Prisoners Dilemma, and both seats of one map give the same table.
// One char per tile: '0' neutral, '1' team A, '2' team B.
// usage (repository root): node exp/cand-stack8/genterrdb.js exp/cand-stack8/bot/terrdb.hpp
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const out = process.argv[2];
if (!out) { console.error('usage: genterrdb.js <out terrdb.hpp>'); process.exit(2); }
const { perGame } = require(path.join(ROOT, 'tools', 'mass_ledger.js'));
const { makeLoader, viewerSource } = require(path.join(ROOT, 'tools', 'top_features.js'));
const load = makeLoader(viewerSource());
// mapdb.hpp order (exp/mapid/genmapdb.js): maps/online-20260927 by file name, then prisoners_dilemma_10 and the four *_b maps
const A = fs.readdirSync(path.join(ROOT, 'maps', 'online-20260927')).filter(x => x.endsWith('.map')).sort().map(f => f.replace(/\.map$/, ''));
const KEYS = [...A, 'prisoners_dilemma_10', 'devil_b', 'queen_of_spades_b', 'schooltime_b', 'slithery_fight_b'];
const dbSrc = fs.readFileSync(path.join(ROOT, 'exp', 'cand-stack8', 'bot', 'mapdb.hpp'), 'utf8');
const dims = [...dbSrc.matchAll(/\{"([^"]+)", (\d+), (\d+),/g)].map(m => ({ name: m[1], W: +m[2], H: +m[3] }));
if (dims.length !== KEYS.length) throw new Error(`mapdb has ${dims.length} maps, expected ${KEYS.length}`);
function terrOf(file) {
  const R = load(file); let T = null, W = 0, H = 0;
  perGame(R, { map: '', variant: 'a' }, { turn(d, r, c) { if (!T) { T = Array.from(c.terr).join(''); W = c.W; H = c.H; } } });
  return { T, W, H };
}
const rows = [];
for (const [i, key] of KEYS.entries()) {
  const b = /_(b|10)$/.test(key);
  const dir = path.join(ROOT, 'exp', b ? 'stack7-b-px4' : 'stack7-a-px4', 'games');
  const seed = b ? 2 : 1;
  const fa = path.join(dir, `proxy4_elim_${key}_A_${seed}`, 'game.replay'), fb = path.join(dir, `proxy4_elim_${key}_B_${seed}`, 'game.replay');
  const ta = terrOf(fa), tb = terrOf(fb);
  if (ta.T !== tb.T) throw new Error('seats disagree on ' + key);
  if (ta.W !== dims[i].W || ta.H !== dims[i].H) throw new Error(`size mismatch ${key}: replay ${ta.W}x${ta.H}, mapdb ${dims[i].name} ${dims[i].W}x${dims[i].H}`);
  rows.push({ key, name: dims[i].name, W: ta.W, H: ta.H, T: ta.T });
  const n = c => ta.T.split('').filter(x => x === c).length;
  console.log(`  ${i} ${dims[i].name} ${key} ${ta.W}x${ta.H}: A ${n('1')} B ${n('2')} neutral ${n('0')}`);
}
for (const [k, a] of [['devil_b', 'devil'], ['queen_of_spades_b', 'queen_of_spades'], ['schooltime_b', 'schooltime'], ['slithery_fight_b', 'slithery_fight'], ['prisoners_dilemma_10', 'prisoners_dilemma']]) {
  const x = rows.find(r => r.key === k), y = rows.find(r => r.key === a);
  console.log(`  ${k} vs ${a}: ${x.T === y.T ? 'same territory' : 'different territory (' + x.T.split('').filter((c, i) => c !== y.T[i]).length + ' tiles)'}`);
}
let s = '// terrdb.hpp — generated by exp/cand-stack8/genterrdb.js from one local replay per table map of mapdb.hpp (same order). Do not edit.\n';
s += '// stack8 F2: the territory of each table map as the mass ledger defines it (tools/mass_ledger.js): a tile belongs to the team whose\n';
s += '// starting bodies are nearer by movement distance (kelp, portals, wrap); equal or unreachable = neutral. One char per tile\n';
s += '// (row-major): \'0\' neutral, \'1\' team A, \'2\' team B.\n';
s += '#pragma once\nnamespace seed0 { namespace terrdb {\nstatic const char* const TERR[] = {\n';
for (const r of rows) s += `  "${r.T}", // ${r.name} (${r.key})\n`;
s += '};\n}} // namespace seed0::terrdb\n';
fs.writeFileSync(out, s);
console.log('wrote', out, (s.length / 1024).toFixed(1) + ' KB');
